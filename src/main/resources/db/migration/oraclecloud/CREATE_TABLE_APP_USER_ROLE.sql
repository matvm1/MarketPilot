CREATE TABLE APP_USER_ROLE (
    ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 1 INCREMENT BY 1) NOT NULL,
    USER_ID NUMBER NOT NULL,
    ROLE_ID NUMBER NOT NULL,
    REGISTRATION_EXPIRATION TIMESTAMP DEFAULT (SYSTIMESTAMP + INTERVAL '30' MINUTE) NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_APP_USER_ROLE PRIMARY KEY (ID),
    CONSTRAINT FK_USER_ROLE_USER FOREIGN KEY (USER_ID)
        REFERENCES APP_USER (ID),
    CONSTRAINT FK_USER_ROLE_ROLE FOREIGN KEY (ROLE_ID)
        REFERENCES APP_ROLE (ID),
    CONSTRAINT UQ_USER_ROLE UNIQUE (USER_ID, ROLE_ID)
);
