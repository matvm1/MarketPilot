CREATE TABLE APP_PENDING_USER_ROLE (
    ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 1 INCREMENT BY 1) NOT NULL,
    PENDING_USER_ID NUMBER NOT NULL,
    ROLE_ID NUMBER NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_APP_PENDING_USER_ROLE PRIMARY KEY (ID),
    CONSTRAINT FK_PENDING_USER_ROLE_USER FOREIGN KEY (PENDING_USER_ID)
        REFERENCES APP_USER (ID),
    CONSTRAINT FK_PENDING_USER_ROLE_ROLE FOREIGN KEY (ROLE_ID)
        REFERENCES APP_ROLE (ID),
    CONSTRAINT UQ_PENDING_USER_ROLE UNIQUE (PENDING_USER_ID, ROLE_ID)
);