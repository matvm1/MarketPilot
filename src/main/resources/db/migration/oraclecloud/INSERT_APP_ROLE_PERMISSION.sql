-- Insert PUBLIC_USER role permissions
INSERT INTO APP_ROLE_PERMISSION (ROLE_ID, PERMISSION_ID)
SELECT r.ID, p.ID
FROM APP_ROLE r
JOIN APP_PERMISSION p ON p.NAME IN (
    'VIEW_QUOTE',
    'VIEW_ARTICLE',
    'VIEW_SECURITY_RATING',
    'CREATE_WATCHLIST',
    'DELETE_WATCHLIST'
)
WHERE r.NAME = 'Public';

