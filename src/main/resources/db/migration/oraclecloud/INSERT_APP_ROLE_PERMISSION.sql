-- Assign all permissions to Admin
INSERT INTO APP_ROLE_PERMISSION (ROLE_ID, PERMISSION_ID)
SELECT r.ID, p.ID
FROM APP_ROLE r
CROSS JOIN APP_PERMISSION p
WHERE r.NAME = 'Admin'
  AND NOT EXISTS (
      SELECT 1 FROM APP_ROLE_PERMISSION rp
      WHERE rp.ROLE_ID = r.ID
        AND rp.PERMISSION_ID = p.ID
  );